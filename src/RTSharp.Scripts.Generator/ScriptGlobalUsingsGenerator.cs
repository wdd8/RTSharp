using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

using System;
using System.Text;

namespace RTSharp.Scripts.Generator
{
    [Generator]
    public class ScriptGlobalUsingsGenerator : IIncrementalGenerator
    {
        private const string ScriptEnvironmentType = "RTSharp.Daemon.RuntimeCompilation.ScriptEnvironment";
        private const string UsingsField = "BuiltInUsingsList";

        public void Initialize(IncrementalGeneratorInitializationContext Context)
        {
            var usings = Context.CompilationProvider.Select((compilation, ct) => {
                var type = compilation.GetTypeByMetadataName(ScriptEnvironmentType);

                if (type == null)
                    return null;

                foreach (var member in type.GetMembers(UsingsField)) {
                    if (member is IFieldSymbol { IsConst: true, ConstantValue: string list })
                        return list;
                }

                return null;
            });

            Context.RegisterSourceOutput(usings, Emit);
        }

        private static void Emit(SourceProductionContext Context, string? Usings)
        {
            if (String.IsNullOrEmpty(Usings))
                return;

            var output = new StringBuilder();
            output.AppendLine("// <auto-generated />");
            output.AppendLine($"// Generated from {ScriptEnvironmentType}.{UsingsField}");
            output.AppendLine();

            foreach (var ns in Usings!.Split(';')) {
                var trimmed = ns.Trim();

                if (trimmed.Length != 0)
                    output.AppendLine($"global using global::{trimmed};");
            }

            Context.AddSource("ScriptGlobalUsings.g.cs", SourceText.From(output.ToString(), Encoding.UTF8));
        }
    }
}
