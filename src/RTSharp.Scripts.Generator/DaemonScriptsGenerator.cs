using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace RTSharp.Scripts.Generator
{
    [Generator]
    public class DaemonScriptsGenerator : IIncrementalGenerator
    {
        private const string ScriptSourceMetadata = "build_metadata.AdditionalFiles.ScriptSource";
        private const string ScriptContractMetadata = "build_metadata.AdditionalFiles.ScriptContract";

        private static readonly Regex ContractPragma = new Regex(@"^#pragma contract (?<name>.+)$", RegexOptions.Multiline);

        private static readonly DiagnosticDescriptor UnsupportedMessageProperty = new DiagnosticDescriptor(
            id: "RTSCRIPT002",
            title: "Script message property cannot be mapped",
            messageFormat: "'{0}' on message '{1}' is a {2}, which is unhandled. Expected a primitive, string, byte[], another record (or array of) in the same contract",
            category: "RTSharp.Scripts",
            defaultSeverity: DiagnosticSeverity.Error,
            isEnabledByDefault: true);

        private static readonly DiagnosticDescriptor MissingContract = new DiagnosticDescriptor(
            id: "RTSCRIPT001",
            title: "Script contract not found",
            messageFormat: "No contract file named '{0}' for script '{1}'. Expected in Scripts\\Contracts\\",
            category: "RTSharp.Scripts",
            defaultSeverity: DiagnosticSeverity.Error,
            isEnabledByDefault: true);

        public void Initialize(IncrementalGeneratorInitializationContext Context)
        {
            var scripts = Context.AdditionalTextsProvider
                .Combine(Context.AnalyzerConfigOptionsProvider)
                .Where(x => x.Right.GetOptions(x.Left).TryGetValue(ScriptSourceMetadata, out var flag) &&
                            flag.Equals("true", StringComparison.OrdinalIgnoreCase))
                .Select((x, ct) => {
                    var fileName = Path.GetFileNameWithoutExtension(x.Left.Path);
                    var name = new StringBuilder(fileName.Length);

                    if (fileName.Length == 0 || !char.IsLetter(fileName[0]) && fileName[0] != '_')
                        name.Append('_');

                    foreach (var ch in fileName)
                        name.Append(char.IsLetterOrDigit(ch) ? ch : '_');

                    return (
                        Name: name.ToString(),
                        Text: x.Left.GetText(ct)?.ToString() ?? "",
                        IsContract: x.Right.GetOptions(x.Left).TryGetValue(ScriptContractMetadata, out var contract) &&
                                    contract.Equals("true", StringComparison.OrdinalIgnoreCase)
                    );
                })
                .Collect();

            Context.RegisterSourceOutput(scripts, Emit);
        }

        private static void Emit(SourceProductionContext Context, ImmutableArray<(string Name, string Text, bool IsContract)> Scripts)
        {
            if (Scripts.IsDefaultOrEmpty)
                return;

            var contracts = new Dictionary<string, string>(StringComparer.Ordinal);

            foreach (var (name, text, isContract) in Scripts) {
                if (!isContract)
                    continue;

                var contract = CSharpSyntaxTree.ParseText(text).GetCompilationUnitRoot();
                var mappings = Mappings(Context, contract);

                contracts[name] = text + Environment.NewLine + mappings;

                if (mappings.Length != 0) {
                    var declared = contract.DescendantNodes().OfType<BaseNamespaceDeclarationSyntax>().FirstOrDefault();

                    Context.AddSource($"{name}.Messages.g.cs", SourceText.From(
                        $"// <auto-generated />{Environment.NewLine}#nullable enable{Environment.NewLine}{Environment.NewLine}" +
                        $"namespace {declared?.Name};{Environment.NewLine}{Environment.NewLine}{mappings}", Encoding.UTF8));
                }
            }

            var output = new StringBuilder();
            output.AppendLine("// <auto-generated />");
            output.AppendLine("#nullable enable");
            output.AppendLine();
            output.AppendLine("namespace RTSharp.Scripts");
            output.AppendLine("{");
            output.AppendLine("    /// <summary>Daemon scripts of this project, as source to push to a daemon</summary>");
            output.AppendLine("    internal static class DaemonScripts");
            output.AppendLine("    {");

            var seen = new HashSet<string>(StringComparer.Ordinal);

            foreach (var (name, text, _) in Scripts.Where(x => !x.IsContract).OrderBy(x => x.Name, StringComparer.Ordinal)) {
                if (!seen.Add(name))
                    continue;

                var spliced = SpliceContracts(Context, name, text, contracts);

                output.AppendLine($"        public const string {name} = {SymbolDisplay.FormatLiteral(spliced, quote: true)};");
            }

            output.AppendLine("    }");
            output.AppendLine("}");

            Context.AddSource("DaemonScripts.g.cs", SourceText.From(output.ToString(), Encoding.UTF8));
        }

        private static string Mappings(SourceProductionContext Context, CompilationUnitSyntax Contract)
        {
            var declared = new HashSet<string>(Contract.DescendantNodes().OfType<RecordDeclarationSyntax>().Select(x => x.Identifier.Text), StringComparer.Ordinal);
            var output = new StringBuilder();

            foreach (var record in Contract.DescendantNodes().OfType<RecordDeclarationSyntax>()) {
                var mapping = ScriptMessageMapping.TryEmit(record, declared, (property, type) =>
                    Context.ReportDiagnostic(Diagnostic.Create(UnsupportedMessageProperty, Location.None, property, record.Identifier.Text, type)));

                if (mapping != null)
                    output.AppendLine(mapping);
            }

            return output.ToString();
        }

        private static string SpliceContracts(SourceProductionContext Context, string Name, string Text, Dictionary<string, string> Contracts)
        {
            var named = new List<string>();

            var stripped = ContractPragma.Replace(Text, match => {
                named.Add(match.Groups["name"].Value.Trim());
                return "";
            });

            if (named.Count == 0)
                return Text;

            var script = CSharpSyntaxTree.ParseText(stripped).GetCompilationUnitRoot();

            foreach (var contractName in named) {
                if (!Contracts.TryGetValue(contractName, out var contractText)) {
                    Context.ReportDiagnostic(Diagnostic.Create(MissingContract, Location.None, contractName, Name));
                    continue;
                }

                var contract = CSharpSyntaxTree.ParseText(contractText).GetCompilationUnitRoot();

                script = script.AddUsings([.. contract.Usings.Where(x => !script.Usings.Any(y => y.Name?.ToString() == x.Name?.ToString()))]);

                var members = contract.Members.Count == 1 && contract.Members[0] is BaseNamespaceDeclarationSyntax contractNamespace ? contractNamespace.Members : contract.Members;

                var target = script.Members.OfType<BaseNamespaceDeclarationSyntax>().FirstOrDefault();

                script = target == null ? script.AddMembers([.. members]) : script.ReplaceNode(target, target.AddMembers([.. members]));
            }

            return script.ToFullString();
        }
    }
}
